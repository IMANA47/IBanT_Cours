## Introduction
Ce travail pratique a pour but de maîtriser les bases du langage OCaml à travers un cas concret : la gestion des notes d’étudiants.  
Nous abordons successivement les affichages, les variables, les références, les structures conditionnelles, les fonctions (simples, d’ordre supérieur, récursives) et le polymorphisme.

